"""Render + Vercel deployment for generated apps.

The Deployment agent uses this module to:
  1. Write real, ready-to-use deploy config into each generated project
     (`render.yaml` Blueprint for the backend + Postgres, `vercel.json` for the
     frontend SPA, and a GitHub Actions workflow that deploys to both).
  2. Optionally perform a REAL deploy when credentials are present:
       - Frontend -> Vercel (via the `vercel` CLI, using VERCEL_TOKEN)
       - Backend  -> Render (via a deploy hook URL, RENDER_DEPLOY_HOOK_URL)
     When no credentials are configured the agent runs the local Docker preview
     instead, but narrates the same Render/Vercel flow.

Everything degrades gracefully: missing CLI/token/network never raises, it just
returns None / False so the caller can fall back.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from typing import Dict, List, Optional

from .config import settings
from .local_deploy import APPS_ROOT, _slug
from .logging_config import log


def _http_client(timeout: float = 20.0):
    """httpx client that honours the insecure-SSL flag for SSL-intercepting
    networks (corporate proxy / antivirus). Dev-only."""
    import httpx

    return httpx.Client(verify=not settings.tls_verify_off, timeout=timeout)


def _service_name(project) -> str:
    return _slug(project.name)


def _db_name(project) -> str:
    return _slug(project.name).replace("-", "_") + "_db"


# --------------------------------------------------------------------------- #
# Capability checks
# --------------------------------------------------------------------------- #
def vercel_configured() -> bool:
    return bool(settings.vercel_token) and shutil.which("vercel") is not None


def render_configured() -> bool:
    return bool(settings.render_deploy_hook_url)


def supabase_configured() -> bool:
    return bool(settings.supabase_url)


def database_provider() -> str:
    """Which platform hosts the database: 'supabase' when configured, else 'render'."""
    return "supabase" if supabase_configured() else "render"


def supabase_health_url() -> Optional[str]:
    """Public Supabase health endpoint (GoTrue /auth/v1/health returns 200, no key)."""
    if not supabase_configured():
        return None
    return settings.supabase_url.rstrip("/") + "/auth/v1/health"


def supabase_ref() -> Optional[str]:
    """The Supabase project ref (the <ref> in https://<ref>.supabase.co)."""
    if not settings.supabase_url:
        return None
    return settings.supabase_url.split("//", 1)[-1].split(".")[0] or None


def supabase_dashboard_url() -> Optional[str]:
    """Link to the Supabase project dashboard (Studio)."""
    ref = supabase_ref()
    return f"https://supabase.com/dashboard/project/{ref}" if ref else None


def render_api_configured() -> bool:
    return bool(settings.render_api_key)


def supabase_database_url(project) -> str:
    """Supabase Postgres connection string (masked) for display/wiring."""
    if settings.supabase_db_url:
        # Mask the password for display while keeping host/db visible.
        url = settings.supabase_db_url
        if "://" in url and "@" in url:
            scheme, rest = url.split("://", 1)
            creds, host = rest.split("@", 1)
            user = creds.split(":", 1)[0]
            return f"{scheme}://{user}:****@{host}"
        return url
    ref = settings.supabase_url.split("//", 1)[-1].split(".")[0] if settings.supabase_url else "project"
    return f"postgresql://postgres:****@db.{ref}.supabase.co:5432/postgres"


