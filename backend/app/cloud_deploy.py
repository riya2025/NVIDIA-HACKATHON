def write_cloud_artifacts(project) -> List[str]:
    """Write Render/Vercel deploy config into the project dir; return rel paths."""
    app_dir: Path = APPS_ROOT / _slug(project.name)
    files: Dict[str, str] = {
        ".gitignore": _GITIGNORE,
        "render.yaml": render_yaml(project),
        "vercel.json": vercel_json(project),
        # Keep the Vercel frontend deploy clean: exclude the backend, CI and
        # deploy-doc dirs so the CLI doesn't auto-detect them as extra services.
        ".vercelignore": "backend\ndeploy\n.github\nnode_modules\n*.md\n.env\n",
        ".github/workflows/deploy.yml": deploy_workflow(project),
        "deploy/README.md": deploy_readme(project),
    }
    written: List[str] = []
    for rel, content in files.items():
        dest = app_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")
        written.append(rel)
    return written


# --------------------------------------------------------------------------- #
# Real deploys (best-effort; only run when configured)
# --------------------------------------------------------------------------- #
def _prepare_vercel_prebuilt(app_dir: Path) -> bool:
    """Lay out the Vercel Build Output API tree (`.vercel/output`) from the
    already-built `dist/`. Deploying this with `--prebuilt` skips Vercel's
    framework detection + build entirely, which sidesteps project-level
    'framework = services' misconfigurations that otherwise break the build.

    Returns True when the prebuilt output is ready."""
    dist = app_dir / "dist"
    if not (dist / "index.html").exists():
        return False
    out_dir = app_dir / ".vercel" / "output"
    static_dir = out_dir / "static"
    # Rebuild the output tree fresh each deploy.
    if out_dir.exists():
        shutil.rmtree(out_dir, ignore_errors=True)
    static_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(dist, static_dir)
    # Build Output API config: serve static files, SPA-fallback the rest to
    # index.html so client-side routing (Hash/Browser router) works on refresh.
    config = {
        "version": 3,
        "routes": [
            {"handle": "filesystem"},
            {"src": "/(.*)", "dest": "/index.html"},
        ],
    }
    (out_dir / "config.json").write_text(json.dumps(config, indent=2), encoding="utf-8")
    return True


def deploy_frontend_vercel(project) -> Optional[str]:
    """Deploy the built frontend to Vercel via the CLI. Returns the prod URL or
    None. Requires VERCEL_TOKEN and the `vercel` CLI on PATH.

    Deploys the prebuilt `dist/` via the Build Output API (`--prebuilt`) so the
    deploy never depends on Vercel's framework auto-detection (which can be stuck
    on 'services' for an existing project and fail the build)."""
    if not vercel_configured():
        return None
    app_dir = APPS_ROOT / _slug(project.name)
    if not app_dir.exists():
        return None
    import os
    import re

    vercel_bin = shutil.which("vercel") or "vercel"
    env = {}
    if settings.vercel_org_id:
        env["VERCEL_ORG_ID"] = settings.vercel_org_id
    if settings.vercel_project_id:
        env["VERCEL_PROJECT_ID"] = settings.vercel_project_id

    proc_env = {**os.environ, **env}
    proc_env["VERCEL_TELEMETRY_DISABLED"] = "1"
    if settings.tls_verify_off:
        # Vercel CLI runs on Node, which uses its own CA bundle and won't trust
        # an SSL-intercepting proxy's cert. Mirror nvidia_insecure_ssl for Node.
        proc_env["NODE_TLS_REJECT_UNAUTHORIZED"] = "0"

    prebuilt = _prepare_vercel_prebuilt(app_dir)
    cmd = [vercel_bin, "deploy", "--prod", "--yes", f"--token={settings.vercel_token}"]
    if prebuilt:
        cmd.append("--prebuilt")
    # CLI 54+ refuses to pick a default team in non-interactive mode for
    # token-authenticated team accounts — pass the scope explicitly.
    if settings.vercel_scope:
        cmd += ["--scope", settings.vercel_scope]
    try:
        result = subprocess.run(
            cmd,
            cwd=str(app_dir),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=600,
            env=proc_env,
        )
    except Exception:  # noqa: BLE001
        return None
    out = (result.stdout or "") + "\n" + (result.stderr or "")
    if result.returncode != 0:
        log.bind(agent="deployment").warning("vercel deploy failed: {}", out[-500:])
        return None
    # CLI 54 prints "Production <url>" and "Aliased <url>" (and sometimes JSON).
    # Prefer the stable aliased production URL; fall back to any *.vercel.app.
    alias = re.search(r"[Aa]liased\s+(https://[^\s\"']+\.vercel\.app)", out)
    if alias:
        return alias.group(1)
    matches = re.findall(r"https://[a-z0-9][a-z0-9.-]*\.vercel\.app", out)
    return matches[0] if matches else None


def trigger_render(project) -> bool:
    """Trigger a Render deploy via the configured deploy-hook URL. Returns True
    on a 2xx response. Render builds asynchronously from the connected repo."""
    if not render_configured():
        return False
    try:
        with _http_client(15.0) as client:
            r = client.post(settings.render_deploy_hook_url)
        return 200 <= r.status_code < 300
    except Exception:  # noqa: BLE001
        return False


def render_backend_url(project) -> str:
    """Conventional Render web-service URL for narration/links."""
    return f"https://{_service_name(project)}-api.onrender.com"


def render_database_url(project) -> str:
    """Render-style Postgres connection string (host is illustrative when the
    real DB hasn't been provisioned by a live Blueprint run)."""
    svc = _service_name(project)
    host = f"dpg-{svc}-db.{settings.render_region}-postgres.render.com"
    return f"postgresql://{settings.db_master_username}:****@{host}:{settings.db_port}/{_db_name(project)}"


# --------------------------------------------------------------------------- #
# Render API backend deploy (free web service, built from a public GitHub repo)
# --------------------------------------------------------------------------- #
_RENDER_API = "https://api.render.com/v1"


def _render_headers() -> dict:
    return {
        "Authorization": f"Bearer {settings.render_api_key}",
        "Accept": "application/json",
        "Content-Type": "application/json",
    }


def _render_owner_id() -> Optional[str]:
    """The workspace (owner) id the new service is created under."""
    try:
        with _http_client(20.0) as client:
            r = client.get(f"{_RENDER_API}/owners?limit=1", headers=_render_headers())
        if r.status_code != 200:
            log.bind(agent="deployment").warning(
                "Render /owners failed: {} {}", r.status_code, r.text[:200]
            )
            return None
        items = r.json()
        if items:
            return items[0]["owner"]["id"]
    except Exception as exc:  # noqa: BLE001
        log.bind(agent="deployment").warning("Render /owners error: {}", exc)
    return None


def _render_service_name(project) -> str:
    import hashlib

    suffix = hashlib.sha1(str(project.id).encode()).hexdigest()[:6]
    base = _slug(project.name)[:24].strip("-") or "app"
    return f"{base}-{suffix}"


def _render_backend_env_vars(database_url: Optional[str]) -> list[dict]:
    """Env vars injected on the Render service. Uses the REAL (unmasked)
    Supabase connection string + keys when Supabase is configured."""
    env: list[dict] = []
    if database_url:
        env.append({"key": "DATABASE_URL", "value": database_url})
    if settings.supabase_url:
        env.append({"key": "SUPABASE_URL", "value": settings.supabase_url})
    if settings.supabase_anon_key:
        env.append({"key": "SUPABASE_ANON_KEY", "value": settings.supabase_anon_key})
    return env


def _render_find_service(name: str, owner_id: str) -> Optional[dict]:
    """Return an existing service dict for this name, or None."""
    try:
        with _http_client(20.0) as client:
            r = client.get(
                f"{_RENDER_API}/services",
                headers=_render_headers(),
                params={"name": name, "ownerId": owner_id, "limit": 1},
            )
        if r.status_code == 200 and r.json():
            return r.json()[0]["service"]
    except Exception as exc:  # noqa: BLE001
        log.bind(agent="deployment").warning("Render list services error: {}", exc)
    return None


def _render_service_url(service: dict, name: str) -> str:
    details = service.get("serviceDetails") or {}
    return details.get("url") or f"https://{name}.onrender.com"


def deploy_backend_render_api(
    project, repo_url: str, branch: str = "main", database_url: Optional[str] = None
) -> Optional[str]:
    """Create (or redeploy) a real Render web service from the public GitHub repo
    and return its public https://<svc>.onrender.com URL, or None.

    The service uses the Docker runtime, builds `backend/Dockerfile` (rootDir
    'backend'), exposes /health, and runs on the free plan. Best-effort.
    """
    if not render_api_configured():
        return None
    owner_id = _render_owner_id()
    if not owner_id:
        return None

    name = _render_service_name(project)
    env_vars = _render_backend_env_vars(database_url)

    # If the service already exists (re-run), trigger a fresh deploy instead.
    existing = _render_find_service(name, owner_id)
    if existing:
        return _render_redeploy(existing, name)

    payload = {
        "type": "web_service",
        "name": name,
        "ownerId": owner_id,
        "repo": repo_url,
        "branch": branch,
        "autoDeploy": "no",  # public-repo services don't support auto-deploy
        "rootDir": "backend",
        "envVars": env_vars,
        "serviceDetails": {
            "runtime": "docker",
            "plan": settings.render_plan,
            "region": settings.render_region,
            "healthCheckPath": "/health",
        },
    }
    try:
        with _http_client(60.0) as client:
            r = client.post(
                f"{_RENDER_API}/services", headers=_render_headers(), json=payload
            )
        if r.status_code in (200, 201):
            body = r.json()
            service = body.get("service", body)
            url = _render_service_url(service, name)
            log.bind(agent="deployment").info("Render service created: {}", url)
            return url
        log.bind(agent="deployment").warning(
            "Render create service failed: {} {}", r.status_code, r.text[:400]
        )
    except Exception as exc:  # noqa: BLE001
        log.bind(agent="deployment").warning("Render create service error: {}", exc)
    return None


def _render_redeploy(service: dict, name: str) -> Optional[str]:
    """Trigger a new deploy for an existing service; return its URL."""
    svc_id = service.get("id")
    url = _render_service_url(service, name)
    if not svc_id:
        return url
    try:
        with _http_client(30.0) as client:
            r = client.post(
                f"{_RENDER_API}/services/{svc_id}/deploys",
                headers=_render_headers(),
                json={"clearCache": "do_not_clear"},
            )
        if r.status_code in (200, 201, 202):
            log.bind(agent="deployment").info("Render redeploy triggered: {}", url)
        else:
            log.bind(agent="deployment").warning(
                "Render redeploy failed: {} {}", r.status_code, r.text[:300]
            )
    except Exception as exc:  # noqa: BLE001
        log.bind(agent="deployment").warning("Render redeploy error: {}", exc)
    return url
