def render_yaml(project) -> str:
    """`render.yaml` Blueprint: Dockerized FastAPI web service + a database.

    When Supabase is configured the backend points at the Supabase DATABASE_URL
    (set as a Render env var / secret); otherwise a Render Managed Postgres is
    declared and wired in automatically.
    """
    svc = _service_name(project)
    use_supabase = supabase_configured()
    head = (
        "# Generated by AI Foundry Deployment Agent.\n"
        "# Render Blueprint: deploys the FastAPI backend (Docker).\n"
        f"# Database: {'Supabase (external DATABASE_URL)' if use_supabase else 'Render Managed Postgres'}.\n"
        "# Create from the Render dashboard: New + > Blueprint, or `render blueprint launch`.\n"
    )
    db_block = (
        ""
        if use_supabase
        else (
            "databases:\n"
            f"  - name: {svc}-db\n"
            f"    plan: {settings.render_db_plan}\n"
            f"    region: {settings.render_region}\n"
            "    postgresMajorVersion: \"16\"\n"
        )
    )
    if use_supabase:
        env_block = (
            "    envVars:\n"
            "      - key: DATABASE_URL\n"
            "        sync: false   # set to your Supabase connection string (secret)\n"
            f"      - key: SUPABASE_URL\n"
            f"        value: {settings.supabase_url}\n"
        )
    else:
        env_block = (
            "    envVars:\n"
            "      - key: DATABASE_URL\n"
            "        fromDatabase:\n"
            f"          name: {svc}-db\n"
            "          property: connectionString\n"
        )
    svc_block = (
        "services:\n"
        "  - type: web\n"
        f"    name: {svc}-api\n"
        "    runtime: docker\n"
        "    dockerfilePath: ./backend/Dockerfile\n"
        "    dockerContext: ./backend\n"
        f"    region: {settings.render_region}\n"
        f"    plan: {settings.render_plan}\n"
        "    healthCheckPath: /health\n"
        "    autoDeploy: true\n"
        + env_block
    )
    return head + db_block + svc_block


def vercel_json(project) -> str:
    """`vercel.json` for a Vite SPA.

    Keep this MINIMAL: Vercel auto-detects the Vite framework from package.json.
    Setting top-level `framework`/`buildCommand`/`outputDirectory` conflicts with
    the CLI's service auto-detection ("...cannot be used with `services`...") and
    breaks `vercel deploy`. The generated app uses HashRouter, so the SPA rewrite
    is the only thing we need (and is harmless)."""
    return (
        json.dumps(
            {"rewrites": [{"source": "/(.*)", "destination": "/index.html"}]},
            indent=2,
        )
        + "\n"
    )


def deploy_workflow(project) -> str:
    """`.github/workflows/deploy.yml` — OPTIONAL manual push-to-deploy template.

    This is a convenience template only: the AI Foundry control plane already
    deploys the frontend (Vercel) and backend (Render) directly via their APIs,
    so this workflow is NOT required. It is therefore:
      * `workflow_dispatch` only (never auto-runs on push), so it can't spam the
        repo with failing runs, and
      * each step is guarded by `if: env.<SECRET> != ''`, so if you DO run it
        without configuring the repo secrets it skips cleanly instead of failing
        with 'You defined "--token", but it's missing a value'.

    To use it: add repo secrets VERCEL_TOKEN (+ optional VERCEL_ORG_ID,
    VERCEL_PROJECT_ID) and/or RENDER_DEPLOY_HOOK_URL, then run it manually from
    the Actions tab.
    """
    return """# Generated by AI Foundry Deployment Agent (OPTIONAL — manual only).
# The AI Foundry control plane already deploys Vercel + Render via their APIs,
# so this workflow is not required. Run it manually from the Actions tab after
# adding the repo secrets below. Steps self-skip when a secret is missing.
name: Deploy (Vercel + Render)

on:
  workflow_dispatch:

jobs:
  frontend-vercel:
    name: Deploy frontend to Vercel
    runs-on: ubuntu-latest
    env:
      VERCEL_TOKEN: ${{ secrets.VERCEL_TOKEN }}
      VERCEL_ORG_ID: ${{ secrets.VERCEL_ORG_ID }}
      VERCEL_PROJECT_ID: ${{ secrets.VERCEL_PROJECT_ID }}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: "20"
      - name: Install Vercel CLI
        if: ${{ env.VERCEL_TOKEN != '' }}
        run: npm install -g vercel
      - name: Deploy to Vercel (production)
        if: ${{ env.VERCEL_TOKEN != '' }}
        run: vercel deploy --prod --yes --token="$VERCEL_TOKEN"
      - name: Skipped (no VERCEL_TOKEN secret)
        if: ${{ env.VERCEL_TOKEN == '' }}
        run: echo "VERCEL_TOKEN secret not set — skipping Vercel deploy."

  backend-render:
    name: Deploy backend to Render
    runs-on: ubuntu-latest
    env:
      RENDER_DEPLOY_HOOK_URL: ${{ secrets.RENDER_DEPLOY_HOOK_URL }}
    steps:
      - name: Trigger Render deploy
        if: ${{ env.RENDER_DEPLOY_HOOK_URL != '' }}
        run: curl -fsSL -X POST "$RENDER_DEPLOY_HOOK_URL"
      - name: Skipped (no RENDER_DEPLOY_HOOK_URL secret)
        if: ${{ env.RENDER_DEPLOY_HOOK_URL == '' }}
        run: echo "RENDER_DEPLOY_HOOK_URL secret not set — skipping Render deploy."
"""


